def load_quant():
    return json.loads((OUT_DIR / "paper_quantitative_reproduction.json").read_text())


def load_bundle_manifest():
    m = json.loads((OUT_DIR / "paper_source_bundle_manifest.json").read_text())
    return {f["bundle"]: f for f in m["files"]}


def load_forensics():
    p = OUT_DIR / "figure_1_5_6_si_forensics.json"
    if p.exists():
        return json.loads(p.read_text())
    return None


def bundle_hash(manifest, name):
    return manifest.get(name, {}).get("original_sha256", "N/A")


def bundle_path(manifest, name):
    return manifest.get(name, {}).get("copied_path", "N/A")


